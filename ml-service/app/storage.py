"""Where the service reads videos and writes clips and thumbnails (decision D7).

Two backends, chosen with ``STORAGE_TYPE`` to match the API's ``app.storage.type``:

- ``local`` (default): a folder shared with the API (``STORAGE_DIR``), for development and
  Docker Compose. Files are read and written in place.
- ``s3``: the private bucket (``S3_BUCKET``). The video is downloaded to a temporary folder,
  media is rendered there and uploaded with server-side encryption (SSE-KMS if
  ``S3_KMS_KEY_ID`` is set, otherwise SSE-S3), and the folder is removed afterwards.
  Credentials come from the default AWS chain (on AWS, the task or instance role).

Keys are always relative paths generated by the API; ``check_key`` refuses anything else.
"""
import os
import shutil
import tempfile
from contextlib import AbstractContextManager, contextmanager
from pathlib import Path
from typing import Iterable, Iterator, Protocol

_CONTENT_TYPES = {".mp4": "video/mp4", ".webm": "video/webm", ".jpg": "image/jpeg"}


class Storage(Protocol):
    def check_key(self, key: str) -> None: ...

    def video(self, key: str) -> AbstractContextManager[Path]:
        """The video as a local file for the duration of the block."""

    def media_dir(self) -> AbstractContextManager[Path]:
        """A folder to render media into; keys are paths relative to it."""

    def publish(self, root: Path, keys: Iterable[str]) -> None:
        """Makes the rendered files under ``root`` available under their keys."""


def _check_relative(key: str) -> None:
    if not key or key.startswith(("/", "\\")) or ".." in key.split("/") or "\\" in key or "\x00" in key:
        raise ValueError("invalid storage key")


class LocalStorage:
    def __init__(self, root: Path):
        self.root = root.resolve()

    def resolve(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root) or path == self.root:
            raise ValueError("storage key points outside the storage folder")
        return path

    def check_key(self, key: str) -> None:
        self.resolve(key)

    @contextmanager
    def video(self, key: str) -> Iterator[Path]:
        path = self.resolve(key)
        if not path.is_file():
            raise FileNotFoundError("video not found in storage")
        yield path

    @contextmanager
    def media_dir(self) -> Iterator[Path]:
        # Media is written straight into the shared folder; nothing to upload.
        yield self.root

    def publish(self, root: Path, keys: Iterable[str]) -> None:
        pass


class S3Storage:
    def __init__(self, bucket: str, region: str | None = None, kms_key_id: str | None = None,
                 endpoint: str | None = None, client=None):
        if not bucket:
            raise RuntimeError("S3_BUCKET is not set")
        self.bucket = bucket
        self.kms_key_id = kms_key_id or None
        if client is None:
            import boto3  # only needed with STORAGE_TYPE=s3

            client = boto3.client("s3", region_name=region, endpoint_url=endpoint or None)
        self.client = client

    def check_key(self, key: str) -> None:
        _check_relative(key)

    @contextmanager
    def video(self, key: str) -> Iterator[Path]:
        self.check_key(key)
        from botocore.exceptions import ClientError

        with _temp_dir("video-") as tmp:
            path = tmp / Path(key).name
            try:
                self.client.download_file(self.bucket, key, str(path))
            except ClientError as exc:
                if exc.response.get("Error", {}).get("Code") in ("404", "NoSuchKey", "NotFound"):
                    raise FileNotFoundError("video not found in storage") from exc
                raise
            yield path

    @contextmanager
    def media_dir(self) -> Iterator[Path]:
        with _temp_dir("media-") as tmp:
            yield tmp

    def publish(self, root: Path, keys: Iterable[str]) -> None:
        extra = ({"ServerSideEncryption": "aws:kms", "SSEKMSKeyId": self.kms_key_id} if self.kms_key_id
                 else {"ServerSideEncryption": "AES256"})
        for key in keys:
            self.check_key(key)
            content_type = _CONTENT_TYPES.get(Path(key).suffix.lower(), "application/octet-stream")
            self.client.upload_file(str(root / key), self.bucket, key,
                                    ExtraArgs=extra | {"ContentType": content_type})


@contextmanager
def _temp_dir(prefix: str) -> Iterator[Path]:
    path = Path(tempfile.mkdtemp(prefix=prefix))
    try:
        yield path
    finally:
        shutil.rmtree(path, ignore_errors=True)


def check_key(key: str) -> None:
    """Validates a key against the configured backend without connecting to it."""
    if os.environ.get("STORAGE_TYPE", "local").lower() == "s3":
        _check_relative(key)
    else:
        _local().check_key(key)


def _local() -> LocalStorage:
    return LocalStorage(Path(os.environ.get("STORAGE_DIR", "../data/storage")))


def from_env() -> LocalStorage | S3Storage:
    """Read from the environment each time, so tests can change it."""
    kind = os.environ.get("STORAGE_TYPE", "local").lower()
    if kind == "s3":
        return S3Storage(os.environ.get("S3_BUCKET", ""), os.environ.get("AWS_REGION"),
                         os.environ.get("S3_KMS_KEY_ID"), os.environ.get("S3_ENDPOINT"))
    if kind != "local":
        raise RuntimeError(f"unknown STORAGE_TYPE {kind!r}")
    return _local()
