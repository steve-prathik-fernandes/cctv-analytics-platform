"""Request and result shapes for the detection service.

Matches section 4 of docs/03-architecture.md (POST /jobs) and the EventSubmission schema in
docs/api/openapi.yaml. Field names are camelCase on the wire to match the Java API.
"""
from datetime import time
from typing import Annotated, Literal
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

from pydantic import AfterValidator, AwareDatetime, BaseModel, ConfigDict, Field, model_validator

Point = tuple[Annotated[float, Field(ge=0, le=1)], Annotated[float, Field(ge=0, le=1)]]

RuleType = Literal["LOITERING", "ZONE_ENTRY", "AFTER_HOURS_VEHICLE"]
EventType = Literal["OBJECT_DETECTED", "LOITERING", "ZONE_ENTRY", "AFTER_HOURS_VEHICLE"]
ObjectLabel = Literal["person", "car", "motorcycle", "bus", "truck"]


def _parse_hhmm(value: str) -> time:
    try:
        return time.fromisoformat(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"expected a time as HH:MM, got {value!r}") from exc


class Zone(BaseModel):
    id: int
    name: str
    polygon: list[Point] = Field(min_length=3)


class Rule(BaseModel):
    id: int
    type: RuleType
    zoneId: int | None = None
    params: dict = Field(default_factory=dict)

    @model_validator(mode="after")
    def check_params(self) -> "Rule":
        if self.type in ("LOITERING", "ZONE_ENTRY") and self.zoneId is None:
            raise ValueError(f"{self.type} rule needs a zoneId")
        if self.type == "LOITERING":
            seconds = self.params.get("minSeconds")
            if not isinstance(seconds, (int, float)) or isinstance(seconds, bool) or seconds <= 0:
                raise ValueError("LOITERING rule needs params.minSeconds > 0")
        if self.type == "AFTER_HOURS_VEHICLE":
            for key in ("start", "end"):
                _parse_hhmm(self.params.get(key))
            tz = self.params.get("timezone", "UTC")
            try:
                ZoneInfo(tz)
            except (ZoneInfoNotFoundError, ValueError) as exc:
                raise ValueError(f"unknown timezone {tz!r}") from exc
        return self


def _safe_key(key: str) -> str:
    # Storage keys are generated by the API, never user file names. Refuse anything that
    # could step outside the storage root.
    if key.startswith(("/", "\\")) or ".." in key.split("/") or "\\" in key or "\x00" in key:
        raise ValueError("invalid storage key")
    return key


class JobRequest(BaseModel):
    jobId: int
    cameraId: int
    videoKey: Annotated[str, Field(min_length=1, max_length=512), AfterValidator(_safe_key)]
    recordedStartAt: AwareDatetime
    frameStride: int = Field(default=3, ge=1, le=60)
    minConfidence: float = Field(default=0.4, ge=0.05, le=0.95)
    zones: list[Zone] = Field(default_factory=list)
    rules: list[Rule] = Field(default_factory=list)

    @model_validator(mode="after")
    def rules_reference_known_zones(self) -> "JobRequest":
        zone_ids = {z.id for z in self.zones}
        for rule in self.rules:
            if rule.zoneId is not None and rule.zoneId not in zone_ids:
                raise ValueError(f"rule {rule.id} refers to unknown zone {rule.zoneId}")
        return self


class BoundingBox(BaseModel):
    """Normalized 0..1 relative to the frame, as in the API contract."""

    x: float
    y: float
    width: float
    height: float


class EventSubmission(BaseModel):
    model_config = ConfigDict(frozen=True)

    eventType: EventType
    objectLabel: ObjectLabel
    trackId: int
    confidence: float
    videoOffsetStartMs: int
    videoOffsetEndMs: int
    bbox: BoundingBox
    zoneId: int | None = None
    ruleId: int | None = None
    thumbnailKey: str | None = None
    clipKey: str | None = None
    # Offset of the highest-confidence frame, used to pick the thumbnail. Internal only:
    # not part of the API contract, so it is left out of what is sent.
    bestOffsetMs: int | None = Field(default=None, exclude=True)


def parse_window(rule: Rule) -> tuple[time, time, str]:
    """Start, end and IANA timezone of an AFTER_HOURS_VEHICLE rule."""
    return (_parse_hhmm(rule.params["start"]), _parse_hhmm(rule.params["end"]),
            rule.params.get("timezone", "UTC"))

