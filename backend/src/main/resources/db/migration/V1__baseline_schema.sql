-- Baseline schema. Matches docs/04-database-design.md (version 0.1).
-- Runs on PostgreSQL and on H2 in PostgreSQL mode (dev profile).
-- ${json_type} is jsonb on PostgreSQL and json on H2; see application*.yml.

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(254) NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    display_name    VARCHAR(120) NOT NULL,
    role            VARCHAR(20)  NOT NULL,
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'OPERATOR'))
);

CREATE TABLE cameras (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    location    VARCHAR(200),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_camera_access (
    user_id     BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    camera_id   BIGINT NOT NULL REFERENCES cameras (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, camera_id)
);

CREATE TABLE zones (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id   BIGINT NOT NULL REFERENCES cameras (id) ON DELETE CASCADE,
    name        VARCHAR(120) NOT NULL,
    polygon     ${json_type} NOT NULL
);

CREATE TABLE event_rules (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id   BIGINT NOT NULL REFERENCES cameras (id) ON DELETE CASCADE,
    -- A zone-scoped rule means nothing without its zone, so it goes with it.
    zone_id     BIGINT REFERENCES zones (id) ON DELETE CASCADE,
    rule_type   VARCHAR(30) NOT NULL,
    params      ${json_type} NOT NULL,
    enabled     BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_event_rules_type CHECK (rule_type IN ('LOITERING', 'ZONE_ENTRY', 'AFTER_HOURS_VEHICLE'))
);

CREATE TABLE videos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- RESTRICT: a camera with footage cannot be deleted until its videos are.
    camera_id           BIGINT NOT NULL REFERENCES cameras (id) ON DELETE RESTRICT,
    uploaded_by         BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    original_filename   VARCHAR(255) NOT NULL,
    storage_key         VARCHAR(512) NOT NULL,
    size_bytes          BIGINT NOT NULL,
    duration_seconds    DOUBLE PRECISION,
    recorded_start_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    uploaded_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_videos_storage_key UNIQUE (storage_key)
);

CREATE TABLE processing_jobs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id        BIGINT NOT NULL REFERENCES videos (id) ON DELETE CASCADE,
    status          VARCHAR(20) NOT NULL,
    model_name      VARCHAR(100) NOT NULL,
    frame_stride    INTEGER NOT NULL DEFAULT 1,
    error_message   VARCHAR(2000),
    event_count     INTEGER NOT NULL DEFAULT 0,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at      TIMESTAMP WITH TIME ZONE,
    finished_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_processing_jobs_status CHECK (status IN ('QUEUED', 'RUNNING', 'DONE', 'FAILED')),
    CONSTRAINT ck_processing_jobs_stride CHECK (frame_stride >= 1)
);

CREATE TABLE events (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id               BIGINT NOT NULL REFERENCES cameras (id) ON DELETE RESTRICT,
    video_id                BIGINT NOT NULL REFERENCES videos (id) ON DELETE CASCADE,
    job_id                  BIGINT NOT NULL REFERENCES processing_jobs (id) ON DELETE CASCADE,
    -- Removing a zone or rule keeps the history; the event just loses the link.
    zone_id                 BIGINT REFERENCES zones (id) ON DELETE SET NULL,
    rule_id                 BIGINT REFERENCES event_rules (id) ON DELETE SET NULL,
    event_type              VARCHAR(30) NOT NULL,
    object_label            VARCHAR(20) NOT NULL,
    track_id                INTEGER,
    confidence              DOUBLE PRECISION,
    started_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at                TIMESTAMP WITH TIME ZONE,
    video_offset_start_ms   INTEGER NOT NULL,
    video_offset_end_ms     INTEGER,
    bbox                    ${json_type},
    thumbnail_key           VARCHAR(512),
    clip_key                VARCHAR(512),
    CONSTRAINT ck_events_type CHECK (event_type IN ('OBJECT_DETECTED', 'LOITERING', 'ZONE_ENTRY', 'AFTER_HOURS_VEHICLE')),
    CONSTRAINT ck_events_label CHECK (object_label IN ('person', 'car', 'motorcycle', 'bus', 'truck'))
);

CREATE TABLE audit_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Nullable for failed logins with no matching user. RESTRICT keeps the
    -- log append-only: a user with audit history is disabled, not deleted.
    user_id         BIGINT REFERENCES users (id) ON DELETE RESTRICT,
    action          VARCHAR(60) NOT NULL,
    resource_type   VARCHAR(60),
    resource_id     BIGINT,
    ip_address      VARCHAR(45),
    details         ${json_type},
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indexes from section 3 of the design. users(email) is covered by uk_users_email.
CREATE INDEX ix_events_camera_started ON events (camera_id, started_at DESC);
CREATE INDEX ix_events_type_started   ON events (event_type, started_at DESC);
CREATE INDEX ix_events_object_label   ON events (object_label);
CREATE INDEX ix_events_job            ON events (job_id);
CREATE INDEX ix_videos_camera_uploaded ON videos (camera_id, uploaded_at DESC);
CREATE INDEX ix_audit_logs_created     ON audit_logs (created_at DESC);
CREATE INDEX ix_audit_logs_user_created ON audit_logs (user_id, created_at DESC);
